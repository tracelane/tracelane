#!/usr/bin/env node
/**
 * Generate / verify `src/eval-manifest.json` — the eval corpus the
 * published `@tracelanedev/mcp` package reports through `list_evals`.
 *
 * WHY THIS EXISTS. `tools/evals.ts` used to carry a hand-written array of
 * 49 eval ids and located eval files by walking up from `__dirname` looking
 * for `evals/pain-points`. Both break the moment the package is installed
 * from npm — the thing PLT-21 makes possible:
 *
 *   1. the array had drifted (49 listed vs 69 pain-point + 10
 *      fault-tolerance on disk), so `list_evals` reported a number that was
 *      wrong by 30 evals, from CODE rather than from a doc; and
 *   2. `npx @tracelanedev/mcp` runs out of `node_modules`, where no
 *      `evals/` directory exists at any depth, so the walk finds nothing.
 *
 * The manifest is generated FROM the tree, committed, and bundled into
 * `dist/` — so the published package reports the real corpus whether or not
 * a repo checkout is anywhere nearby.
 *
 * Modes:
 *   --write     regenerate the manifest from evals/ (what a dev runs)
 *   --check     fail non-zero if the committed manifest is stale (prebuild)
 *   --selftest  prove --check BLOCKS on a stale / missing manifest
 *
 * `--check` fails CLOSED: a manifest that cannot be read, parsed or matched
 * is a failure, never a silent pass.
 */

import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	readdirSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(HERE, "..");
const REPO_ROOT = resolve(PKG_ROOT, "..", "..");
const MANIFEST_PATH = join(PKG_ROOT, "src", "eval-manifest.json");

/** Suite directory -> the key it appears under in the manifest. */
const SUITES = [
	["pain-points", "pain-points"],
	["fault-tolerance", "fault-tolerance"],
];

const EVAL_SUFFIX = ".eval.ts";

/**
 * Scan `evals/` and build the manifest object.
 *
 * Throws when `evals/` is absent — a build that cannot see the corpus must
 * not quietly emit an empty manifest (that is the same silent-drift failure
 * this script exists to end).
 */
function scan(repoRoot) {
	const evalsDir = join(repoRoot, "evals");
	if (!existsSync(evalsDir)) {
		throw new Error(
			`evals/ not found at ${evalsDir} — refusing to emit an empty eval manifest`,
		);
	}
	/** @type {Record<string, {id: string, path: string}[]>} */
	const suites = {};
	for (const [dir, key] of SUITES) {
		const abs = join(evalsDir, dir);
		if (!existsSync(abs)) {
			throw new Error(`expected eval suite directory is missing: ${abs}`);
		}
		suites[key] = readdirSync(abs)
			.filter((f) => f.endsWith(EVAL_SUFFIX))
			.map((f) => ({
				id: f.slice(0, -EVAL_SUFFIX.length),
				path: `evals/${dir}/${f}`,
			}))
			.sort((a, b) => a.id.localeCompare(b.id));
	}
	const total = Object.values(suites).reduce((n, v) => n + v.length, 0);
	return {
		_comment:
			"GENERATED by apps/mcp/scripts/gen-eval-manifest.mjs — do not hand-edit. Run `pnpm --filter @tracelanedev/mcp gen:evals`.",
		total,
		suites,
	};
}

function serialize(manifest) {
	return `${JSON.stringify(manifest, null, "\t")}\n`;
}

function write(repoRoot = REPO_ROOT, manifestPath = MANIFEST_PATH) {
	const body = serialize(scan(repoRoot));
	mkdirSync(dirname(manifestPath), { recursive: true });
	writeFileSync(manifestPath, body);
	return body;
}

/** @returns {{ok: true} | {ok: false, reason: string}} */
function check(repoRoot = REPO_ROOT, manifestPath = MANIFEST_PATH) {
	let expected;
	try {
		expected = serialize(scan(repoRoot));
	} catch (err) {
		return { ok: false, reason: err instanceof Error ? err.message : `${err}` };
	}
	if (!existsSync(manifestPath)) {
		return { ok: false, reason: `manifest missing at ${manifestPath}` };
	}
	const actual = readFileSync(manifestPath, "utf8");
	if (actual !== expected) {
		let detail = "";
		try {
			const a = JSON.parse(actual).total;
			const b = JSON.parse(expected).total;
			detail = ` (manifest says ${a} evals, evals/ holds ${b})`;
		} catch {
			detail = " (manifest is not parseable JSON)";
		}
		return {
			ok: false,
			reason: `eval manifest is STALE${detail} — run \`pnpm --filter @tracelanedev/mcp gen:evals\``,
		};
	}
	return { ok: true };
}

// ---------------------------------------------------------------------------
// --selftest: prove --check BLOCKS. A gate never observed failing is not a
// gate (CLAUDE.md §1). Each case plants ONE violation in a scratch copy of
// the tree and asserts the real `--check` path rejects it.
// ---------------------------------------------------------------------------

function selftest() {
	const scratch = mkdtempSync(join(tmpdir(), "mcp-eval-manifest-selftest-"));
	let failures = 0;
	const expect = (name, res, shouldBlock) => {
		const blocked = !res.ok;
		if (blocked === shouldBlock) {
			console.log(
				`  PASS  ${name} — ${blocked ? `BLOCKED: ${res.reason}` : "allowed"}`,
			);
		} else {
			failures += 1;
			console.error(
				`  FAIL  ${name} — expected ${shouldBlock ? "BLOCK" : "ALLOW"}, got ${
					blocked ? `BLOCK (${res.reason})` : "ALLOW"
				}`,
			);
		}
	};

	try {
		// Fixture tree: two suites, three evals.
		const fakeRepo = join(scratch, "repo");
		mkdirSync(join(fakeRepo, "evals", "pain-points"), { recursive: true });
		mkdirSync(join(fakeRepo, "evals", "fault-tolerance"), { recursive: true });
		writeFileSync(join(fakeRepo, "evals", "pain-points", "PP-A1.eval.ts"), "");
		writeFileSync(join(fakeRepo, "evals", "pain-points", "PP-A2.eval.ts"), "");
		writeFileSync(
			join(fakeRepo, "evals", "fault-tolerance", "FT-01.eval.ts"),
			"",
		);
		const manifest = join(scratch, "eval-manifest.json");

		// 1. NEGATIVE — no manifest at all must block.
		expect("missing manifest", check(fakeRepo, manifest), true);

		// 2. POSITIVE — a freshly written manifest must pass (proves the gate
		//    is not simply always-red, which would make case 1 meaningless).
		write(fakeRepo, manifest);
		expect("freshly generated manifest", check(fakeRepo, manifest), false);

		// 3. NEGATIVE — a new eval on disk with a stale manifest must block.
		//    This is the real drift that shipped: 49 ids listed, 79 on disk.
		writeFileSync(join(fakeRepo, "evals", "pain-points", "PP-A3.eval.ts"), "");
		expect(
			"eval added, manifest not regenerated",
			check(fakeRepo, manifest),
			true,
		);

		// 4. NEGATIVE — corrupt manifest must block, not throw past the gate.
		write(fakeRepo, manifest);
		writeFileSync(manifest, "{ not json");
		expect("unparseable manifest", check(fakeRepo, manifest), true);

		// 5. NEGATIVE — evals/ missing entirely must block (never emit empty).
		expect("evals/ absent", check(join(scratch, "nope"), manifest), true);
	} finally {
		rmSync(scratch, { recursive: true, force: true });
	}

	if (failures > 0) {
		console.error(`\nselftest FAILED (${failures} case(s))`);
		process.exit(1);
	}
	console.log(
		"\nselftest OK — --check blocks on stale/missing/corrupt manifests",
	);
}

// ---------------------------------------------------------------------------

const mode = process.argv[2] ?? "--check";
switch (mode) {
	case "--write": {
		write();
		const m = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
		console.log(`wrote ${MANIFEST_PATH} — ${m.total} evals`);
		break;
	}
	case "--check": {
		const res = check();
		if (!res.ok) {
			console.error(`eval manifest check FAILED: ${res.reason}`);
			process.exit(1);
		}
		console.log("eval manifest is current");
		break;
	}
	case "--selftest":
		selftest();
		break;
	default:
		console.error(`unknown mode "${mode}" (--write | --check | --selftest)`);
		process.exit(2);
}
