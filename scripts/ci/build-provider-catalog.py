#!/usr/bin/env python3
"""Generate the gateway's provider catalog and model price table.

GWY-42. Adding a provider used to cost ~15 lines of Rust across six files plus
~10 count/claim edits across six more — a struct field, five `match` arms, a
BYOK allowlist, a TS dropdown const, three CI-enforced doc comments. This script
makes it a row in a data file.

FOUR OUTPUTS, all checked in, all re-derived by `--check`:

  crates/gateway/providers.tsv     one row per OpenAI-compatible provider
  crates/gateway/model_prices.tsv  one row per priced model
  apps/web/.../provider-catalog.generated.ts   the dashboard BYOK dropdown
  the provider tables inside docs/guides/providers.md + apps/docs/providers.mdx

The two doc pages used to enumerate the catalog BY HAND under headings that
carried their own counts — "Dedicated adapters (7)", "OpenAI-compatible
adapters (28)". Both were wrong: the dedicated table said seven and listed six,
omitted Vertex, and counted `openai`, which is a catalog row and not a native
adapter at all. Worse, `check-provider-count.py` could not see either heading —
a count inside parentheses matches none of its claim shapes — so the guard
exited 0 while both published pages lied by 134 entries. The enumeration is
generated between markers now, and the prose around it names no bare count.

TWO INPUTS, and the split matters:

  1. THE PROVIDERS THAT ALREADY ROUTE come from `providers.tsv` ITSELF (see
     `parse_existing`). Their base URLs, env vars and model prefixes are running
     in production and are known-good; taking them from an external catalog
     would silently re-point live traffic. This script therefore treats the
     checked-in rows as authoritative and refuses to overwrite a single field.
     That is what makes a refresh behaviour-preserving rather than merely
     plausible. The FIRST generation bootstrapped these rows out of the
     hand-written `match` arms in `providers/mod.rs`; that code is gone.

  2. NEW PROVIDERS come from models.dev's `api.json` (MIT, Copyright (c) 2025
     models.dev — see crates/gateway/NOTICE-models.dev). It is the neutral
     third-party catalog: 191 providers (provider-count-exempt: that is
     models.dev's own count, not ours), each with a base URL, a key env var, an
     OpenAI-compat marker and per-model pricing. LiteLLM's equivalent file is
     also MIT and was considered; models.dev was chosen because it is not a
     direct competitor's artifact. OpenRouter's /api/v1/models was rejected
     outright — its Terms prohibit automated copying.

A new provider gets ONLY a namespaced `<id>/` prefix, never a bare model-name
prefix. A bare prefix is how `llama-3.3-70b` silently dispatched to Groq with
Groq's key while its BYOK row said "anthropic" (the B-126 class), and 139 new
rows is 139 chances to do it again. The six bare-prefix providers we already
have keep theirs, because they are already live.

Usage:
    build-provider-catalog.py            regenerate from a fresh fetch
    build-provider-catalog.py --check    fail if the checked-in files are stale
    build-provider-catalog.py --selftest prove the guards refuse bad input
"""

