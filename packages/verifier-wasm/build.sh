#!/usr/bin/env bash
# Build the verifier for the browser and regenerate web/pkg/.
# Needs: the wasm32-unknown-unknown target, clang, node, and wasm-bindgen-cli at
# the version pinned in Cargo.toml (cargo install --locked wasm-bindgen-cli --version 0.2.120).
set -euo pipefail
cd "$(dirname "$0")"
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$PWD/target}"
cargo build --release --locked --target wasm32-unknown-unknown -j"${JOBS:-2}"
rm -rf web/pkg
wasm-bindgen --target web --no-typescript --out-dir web/pkg \
  "$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/tracelane_verifier_wasm.wasm"
# Embed the binary as a script so the page never fetches it (CSP connect-src 'none').
node -e '
const fs = require("fs");
const wasm = fs.readFileSync("web/pkg/tracelane_verifier_wasm_bg.wasm");
const hash = require("crypto").createHash("sha256").update(wasm).digest("hex");
fs.writeFileSync("web/pkg/wasm-bytes.js",
  `// Generated by build.sh. ${wasm.length} bytes, sha256 ${hash}\nexport default "${wasm.toString("base64")}";\n`);
fs.rmSync("web/pkg/tracelane_verifier_wasm_bg.wasm");
console.log(`release wasm: ${wasm.length} bytes, sha256 ${hash}`);
'
